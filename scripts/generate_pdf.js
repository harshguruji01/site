function generateHTML(inputFile, outputFile) {
    console.log("Reading Markdown from: " + inputFile);
    const mdContent = fs.readFileSync(inputFile, 'utf-8');
    
    const htmlBody = markdownToHTML(mdContent);
    
    const finalHTML = `
    <!DOCTYPE html>
    <html lang="en">
    <head>
        <meta charset="UTF-8">
        <title>NCERT PDF Document</title>
        ${cssTemplate}
    </head>
    <body>
        <div class="page">
            ${htmlBody}
            
            <div class="footer">
                <span>HarshGuruJi Learning Hub | NCERT Aligned Resource</span>
                <span>Generated by System</span>
            </div>
        </div>
        <script>
            // Auto-trigger print dialog for saving to PDF
            // window.onload = () => window.print();
        </script>
    </body>
    </html>
    `;
    
    fs.writeFileSync(outputFile, finalHTML, 'utf-8');
    console.log("Successfully generated print-ready HTML: " + outputFile);
    console.log("-> Open this HTML file in Chrome and press Ctrl+P to save as a perfectly styled A4 PDF!");
}

