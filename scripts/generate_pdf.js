// VERY SIMPLE markdown to HTML converter for the specific HarshGuruJi format
function markdownToHTML(markdown) {
    let html = markdown;
    
    // Convert Headers
    html = html.replace(/^### (.*$)/gim, '<h3>$1</h3>');
    html = html.replace(/^## (.*$)/gim, '<h2>$1</h2>');
    html = html.replace(/^# (.*$)/gim, '<h1>$1</h1>');
    
    // Convert Bold & Italics
    html = html.replace(/\*\*(.*?)\*\*/g, '<strong>$1</strong>');
    html = html.replace(/\*(.*?)\*/g, '<em>$1</em>');
    
    // Convert Tables (Simple)
    html = html.replace(/\|(.+)\|/g, function(match, content) {
        if (content.includes('---')) return ''; // Skip separator
        const cells = content.split('|').map(c => `<td>${c.trim()}</td>`).join('');
        return `<tr>${cells}</tr>`;
    });
    // Wrap adjacent trs in table
    html = html.replace(/(<tr>.*?<\/tr>\n?)+/g, '<table class="ncert-table">$&</table>');
    html = html.replace(/<td>\*\*(.*?)\*\*<\/td>/g, '<th>$1</th>'); // Hack for table headers
    
    // Checkboxes
    html = html.replace(/- \[ \] (.*)/g, '<div class="checkbox">◻ $1</div>');
    html = html.replace(/- \[x\] (.*)/g, '<div class="checkbox">✅ $1</div>');

    // Bullet Points
    html = html.replace(/^- (.*$)/gim, '<li>$1</li>');
    html = html.replace(/(<li>.*<\/li>\n?)+/g, '<ul>$&</ul>');

    // Horizontal Rules
    html = html.replace(/^---$/gim, '<hr>');

    // Paragraphs
    html = html.split('\n').map(line => {
        if (line.trim() === '' || line.startsWith('<') || line.startsWith('⚠️') || line.startsWith('✅')) {
            return line;
        }
        return `<p>${line}</p>`;
    }).join('\n');

    return html;
}

